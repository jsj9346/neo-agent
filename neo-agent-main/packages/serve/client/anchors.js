/**
 * 화면이 지는 **앵커 이름의 닫힌 집합** — 정본은 `docs/WEB-UI.md` §9.4 결정 7이다.
 *
 * 그 결정이 층을 갈랐다. 생성 도구가 뽑는 것은 정적 화면이고 프레임을 DOM에 그리는 층은
 * 이 레포가 소유하므로, 화면이 지는 것은 *"자리(앵커)만 제공"*이고 `/client/`의 모듈이
 * 그 자리를 채운다. 그래서 *"앵커 이름의 닫힌 집합은 이 레포가 정본으로 들고"* 그
 * *"자리는 `packages/serve/client/`의 상수"*다 — 이 파일이 그 자리다. 원격 시안 프롬프트는
 * 이 집합을 **인자로** 받는다 — §9.4 결정 7이 §9.3에서 끌어온
 * *"프롬프트가 나르는 것은 «이 모듈을 쓴다»이고 계약 셋의 내용이 아니다"*가 여기서 실물을
 * 얻는 자리다.
 *
 * **이 파일은 화면이 아니고 배선도 아니다.** 드는 것은 이름뿐이고, 그 이름으로 DOM을 찾는
 * 코드는 여기 없다 — 오늘 이 상수를 받아 가는 것은 `packages/serve/test/`의 계약 테스트뿐이고,
 * 배선(`packages/serve/client/wiring.js`)이 이 파일에서 들여오는 것은 **타입**이지 이 상수가
 * 아니다. 그것이 결함이 아닌 이유는 §9.4 결정 7의 순서다: 이름이 상수로 먼저 서야 프롬프트가
 * 인자를 갖고, 화면이 그 이름을 들고 온 뒤에 배선이 붙는다. **소비자의 수는 적지 않는다** —
 * 그 수가 느는 것은 이 상수의 계약이 아니라 사이클의 진행이고, 적어 두면 곧 낡는다.
 *
 * ## 표기는 `id="<이름>"` 하나다
 *
 * 화면의 HTML에서 앵커는 `id` 속성으로 나타난다. `data-*`를 **함께** 받지 않는 이유는
 * 대조의 술어가 하나로 닫히기 때문이다 — 표기가 둘이면 전수 대조가 둘 다 받아야 하고, 그
 * 순간 «어느 쪽으로 써도 된다»가 규격이 되어 프롬프트의 인자가 흐려진다.
 *
 * ## 앵커는 값과 무관하게 **항상** 존재한다
 *
 * 배선이 내용을 채우고 비운다. 이 규율이 필요한 자리가 안전 사실 둘이다 —
 * `CLI-INTERFACE.md` §7.1이 자기 상태줄에 대해 *"두 계약 항목이 켜져 있을 때(기본값일 때)는
 * 표시하지 않는다."*를 계약으로 들었고, 생성 도구가 그것을 **조건부 마크업**으로 옮기면
 * 옳은 화면이 아래 전수 대조에서 붉는다. 자리는 늘 있고 비어 있을 수 있다.
 *
 * **§9.4 결정 11이 이 자리를 확정했다** (2026-08-27). 결정 10이 §7.1의 그
 * 「기본값이면 표시하지 않는다」를 승계하는지가 한때 두 문서 어디에도 없었고, 결정 11이
 * **두 층을 갈라** 닫았다 — 승계하는 것은 표시의 내용이고 앵커의 자리가 아니다.
 *
 * - **내용은 승계한다.** *"§7.1이 그 조항에 댄 근거는 대비의 보존이다"*이고
 *   *"그 근거는 상태줄의 1행 제약에서 나오지 않으므로"* *"호스트를 가리지 않는다"*. 그래서 웹
 *   화면도 두 항목이 기본값일 때 그 사실을 표시하지 않는다.
 * - **자리는 승계하지 않는다** — *"앵커는 값과 무관하게 항상 있다."*
 *   그렇게 고른 것이 아니라 고를 여지가 없다 —
 *   *"§9가 템플릿 엔진과 서버 사이드 렌더링을 두지 않기로 했으므로 반입된 화면은 정적 파일 하나이고"*
 *   설정을 모른다. 즉
 *   *"조건부 마크업은 이 배치에서 표현 불가능하고, 조건을 아는 유일한 층은 스냅샷을 받는 배선이다."*
 *   따라서 *"앵커를 안 든 화면은 옳은 화면이 아니라 규격 미달이고"* 아래 전수 대조가 그것을
 *   붉히는 것이 옳다. *"비어 있는 자리는 이 화면의 정상 상태다."*
 *
 * 확정된 값은 이 파일이 마커를 달고 서 있던 것과 같다. **그래도 마커는 걷는다** — 값이 같아도
 * 마커가 남으면 다음이 그 칸을 다시 열고, 결정 11이 그 이유로 이 파일을 이름으로 지목했다.
 *
 * **그 표시를 판정하는 코드는 여기 없다.** 결정 11이 *"모집단은 화면이 아니라 배선이다"*로
 * 그 층을 지목했고 실물은 `packages/serve/client/wiring.js`다 — 이름의 정본은 이 파일이고,
 * 그 이름을 채우는가의 판정은 저기다.
 *
 * ## 앵커를 주는 자리의 규칙 — 개수가 하나로 고정된 자리에만
 *
 * 0..N인 것(승인 목록 같은)은 **컨테이너 하나만** 앵커이고 그 안의 항목은 배선이 만든다.
 * 개수가 변하는 자리에 이름을 주면 그 이름이 곧 «몇 개인가»의 사본이 되고, 사본은 낡는다.
 *
 * ## 무엇이 이 목록을 낡지 않게 하는가 — 그리고 무엇은 못 잡는가
 *
 * 셋이 있고 세 번째가 오늘 힘이 없다.
 *
 * 1. **아래 표와 유니온이 서로를 강제한다.** 표는 `Record<AnchorName, true>`라 키가 빠지면
 *    미충족이고 유니온 밖의 키를 더하면 초과 속성이라, 양방향으로 붉어진다(`protocol.js`의
 *    `STATE_KINDS`가 쓴 규율과 같다). **다만 그 규율의 힘이 여기서는 절반이다** — 그쪽의
 *    유니온은 `../src/protocol.ts`가 정의하는 남의 것이라 서버가 갈리면 붉는데, 여기 유니온은
 *    이 파일이 스스로 적은 것이라 **둘을 함께 고치면 아무것도 안 붉는다.** 이 축이 재는 것은
 *    «표와 유니온이 어긋나지 않음»이고 «목록이 화면의 요구와 맞음»이 아니다.
 * 2. **전수 대조가 화면 쪽에서 잰다** — `packages/serve/test/anchors.contract.test.ts`가
 *    §9.4 결정 8을 진다. 매니페스트의 `generated` HTML 문서 각각에 대해 아래 **모든** 이름이
 *    `id="<이름>"`으로 실재하는가를 묻고, 못 찾으면 붉는다.
 * 3. **그 대조는 자산이 실재할 때만 힘을 갖는다.** 오늘 `generated` 엔트리가 0건이라(§9.4가
 *    *"오늘 반입할 수 있는 화면이 원격에 0장이다"*를 스스로 적었다) 그 축의 모집단이 공집합이고,
 *    공집합에서 참이다. **즉 이 목록이 화면의 요구보다 모자란지는 오늘 아무 기계도 못 잰다** —
 *    모자람이 드러나는 자리는 원격 프롬프트가 이 인자를 쓰는 때이고, 남음이 드러나는 자리는
 *    화면이 온 뒤 그 대조가 필요 이상으로 좁게 붉는 때다.
 *
 * 그리고 이 대조가 재는 것은 **이름의 존재**뿐이다 — §9.4 결정 8이 *"이름의 존재이지 그 자리가
 * 옳은가가 아니다"*로 그 한계를 스스로 적었고, 뒤엣것은 루트 `MILESTONE.md`의 C2(브라우저
 * 검증)가 진다. 적어 두지 않으면 다음이 이 상수와 그 그린을 «화면이 옳다»로 읽는다.
 */

