/**
 * 주입 ③ — 요청 id 발급. **수단은 세부다**(결정 10 · §12). 단조 카운터인 것은 한 문서 안에서
 * 유일하면 충분하기 때문이고, 요청의 짝을 맞추는 것은 서버가 §6대로 같은 `id`를 돌려주는
 * 것뿐이다.
 */
let issued = 0;
const nextRequestId = () => {
  issued += 1;
  return `c${issued}`;
};

/** @type {ScreenState} */
let state = INITIAL_SCREEN_STATE;

/**
 * 멈춘 뒤의 배선이 갈아 끼우는 자리. 아무것도 안 한다.
 *
 * **이것이 계약 ⑥의 «멈춤 표시»다.** 불리언을 두고 자리마다 되물으면 그 물음이 부트의
 * 분기가 되고 결정 12의 *"판정은 0이다"*가 무뎌진다. 자리를 갈아 끼우면 아무것도 묻지 않고
 * *"더 이상 어떤 신호도 접지 않으며"*가 참이 된다.
 */
const NOTHING = () => {};

/**
 * 멈췄다는 자국의 문면. **값은 세부다**(§12) — 계약인 것은 *"멈췄다는 사실이 화면에 선다"*
 * 하나다. §8.1이 이 결함에 대해 *"회복 수단은 새로고침이고, 이 결함은 그 처방이 실제로 듣는
 * 드문 자리다."*를 들었으므로 그 처방을 문면에 함께 적는다.
 */
const STOPPED_NOTICE = "화면을 그리지 못해 멈췄습니다. 페이지를 새로고침하세요.";

/** 열린 스트림을 닫는 자리. 스트림이 서기 전에는 닫을 것이 없다 */
let closeStream = NOTHING;

/**
 * 배선의 **종단** — 정본은 §8.1 계약 ⑥이고 배치는 §9.6 결정 13이다.
 *
 * 계약 ⑥이 셋을 든다:
 * *"화면 층이 던지면 배선은 그 자리에서 멈춘다 — 스트림을 닫고, 더 이상 어떤 신호도 접지
 * 않으며, 멈췄다는 사실이 화면에 선다."* 이 함수가 그 셋이다.
 *
 * **판정은 0이다**(결정 13). *"무엇이 던졌는지 값을 보고 갈래를 고르지 않는다 — 처분이 하나라
 * 고를 것이 없다."* 그래서 잡은 값을 인자로 받지도 않는다.
 *
 * **자국이 던진 층을 안 거친다**(계약 ⑥). `markStopped`는 접기도 뷰도 안 지나고 앵커 하나에
 * 문면을 쓴다 — 던진 것이 그 둘 중 하나이므로 거치면 같은 실패에 다시 걸린다(결정 13).
 *
 * **재진입 가드를 따로 두지 않는다**(결정 13). 두어야 하는 배치는 *"잡은 것을 다시 상태로
 * 접어 결함으로 그리는 갈래"*이고 §8.1이 그것을 기각했다. 여기서 갈아 끼우는 둘은 그 가드가
 * 아니라 계약 ⑥의 *"더 이상 어떤 신호도 접지 않으며"*와 *"스트림을 닫고"*의 실물이다.
 *
 * @returns {void}
 */
const halt = () => {
  push = NOTHING;
  startStream = NOTHING;
  closeStream();
  markStopped(anchors, STOPPED_NOTICE);
};

/**
 * 신호 하나를 접고 그린다. **접기 → 뷰 → 그리기가 이 한 줄에 있다**(결정 1) — 그리는 자리가
 * 하나인 것이 「화면은 상태의 함수다」의 실물이고, 콜백마다 그리면 그 자리가 다섯이 된다
 * (결정 3이 기각한 갈래).
 *
 * **던짐을 여기서 잡는다** (§8.1 계약 ⑥ · 결정 13 — *"잡는 자리는 부트 하나다."*). 층 셋을
 * 잇는 자리가 부트이므로 *"프레임에서 온 신호든 제스처에서 온 신호든 응답에서 온 신호든 전부
 * 그 한 줄을 지난다."* 던짐마다 자리를 두면 「어디서 잡히는가」가 다시 다섯이 된다.
 *
 * **이 자리는 갈아 끼워진다.** 멈춘 뒤에는 `NOTHING`이라 접지도 그리지도 않는다 — 계약 ⑥의
 * *"더 이상 어떤 신호도 접지 않으며"*가 그것이다. 그리고 그 갈아 끼움이 결정 13의
 * *"한 번뿐이다."*를 구조로 만든다.
 *
 * @param {WiringSignal} signal
 * @returns {void}
 */
let push = (signal) => {
  try {
    state = foldSignal(state, signal);
    paint(anchors, viewOf(state), create);
  } catch {
    halt();
  }
};

/**
 * 요청 하나를 보내고 그 **결과를 급수한다** (결정 6 — *"요청의 응답을 버리지 않는다"*).
 *
 * 본문 텍스트를 읽어 그대로 접기 층에 넘기고, 전송이 거부하면 그 사실을 넘긴다. **여기서
 * 갈래를 고르지 않는다** — 성공인가 실패인가는 접기가 `readFrame`으로 판정한다(결정 12의
 * *"판정은 0이다"*).
 *
 * @param {string} requestId
 * @param {RequestFrame} frame
 * @returns {void}
 */
const deliver = (requestId, frame) => {
  void sendRequest(frame)
    .then((response) => response.text())
    .then(
      (body) => {
        push({ kind: "response_body", requestId, body });
      },
      (reason) => {
        push({ kind: "request_rejected", requestId, reason: String(reason) });
      },
    );
};

/**
 * 스트림을 열고 **그 닫개를 부트가 쥔다**. 오늘까지 이 반환을 버리고 있었고, 계약 ⑥의
 * *"스트림을 닫고"*가 쥘 것을 요구한다.
 *
 * 콜백 다섯이 그대로 알파벳의 다섯 갈래가 된다(결정 3). `onGap`이 나르는 `StreamState`를
 * 안 쓰는 것은 그 값을 갈라 읽는 것이 부트의 판정이 되기 때문이다.
 *
 * **이 자리도 갈아 끼워진다.** 최초 그리기가 던지면 그 시점에 스트림이 아직 없어 닫을 것이
 * 없고(그래서 `closeStream`이 `NOTHING`이다), 그 뒤에 이 자리가 그대로 돌면 «멈춘» 배선이
 * 스트림을 새로 여는 상태가 된다 — 계약 ⑥에서 «닫는다»는 그 순서에서 «안 연다»를 함께
 * 뜻한다. 갈아 끼우면 순서를 묻지 않고 둘 다 참이다.
 *
 * @returns {void}
 */
let startStream = () => {
  closeStream = openStream({
    onEvent: (event) => {
      push({ kind: "event", event });
    },
    onEffect: (effect) => {
      push({ kind: "effect", effect });
    },
    onFault: (fault) => {
      push({ kind: "fault", fault });
    },
    onGap: () => {
      push({ kind: "gap" });
    },
    onOffStreamFrame: (frameType) => {
      push({ kind: "off_stream_frame", frameType });
    },
  }).close;
};

// 리스너 등록 — 제스처는 신호가 되고, 같은 자리에서 요청이 나간다. 제스처가 트랜스크립트에
// 아무것도 안 더하는 것이 결정 5의 낙관적 그리기 부재다.
attachPromptSubmit(anchors, (text) => {
  const requestId = nextRequestId();
  push({ kind: "prompt_submitted", requestId });
  deliver(requestId, promptRequest(requestId, text));
});

attachApprovalAnswers(anchors, (approvalId, answer) => {
  const requestId = nextRequestId();
  push({ kind: "approval_answered", requestId, approvalId, answer });
  deliver(requestId, approvalRequest(requestId, approvalId, answer));
});

// 첫 그리기. 스트림을 열기 전에 «연결 중»이 서야 첫 프레임까지의 창이 빈 화면이 아니다
// (`ARCHITECTURE.md` §2.6).
//
// **이 자리도 잡는다** (§8.1 계약 ⑥). `push`를 안 지나는 유일한 그리기이고, 계약 ⑥의 문면이
// *"화면 층이 던지면"*이라 부트의 어느 호출인가를 한정하지 않는다. 여기서 던지면 자국 없이
// 부트가 죽어 그 계약이 없애려던 상태가 그대로 남는다.
//
// **오늘 이 자리의 초기 상태는 클라이언트 소유다.** `INITIAL_SCREEN_STATE`는 서버가 준 것을
// 하나도 안 들었으므로 §8.1이 이 경로의 유일한 발현으로 든 것(*"서버가 새 코어로 다시 뜬 뒤에도
// 열려 있던 탭"*)이 여기엔 원리적으로 안 닿는다 — 미지 판별자가 올 자리가 없다. **그것은 덮지
// 않는 근거가 아니라 적을 사실이다**(§2.3) — 안 적으면 다음이 이 자리를 「이미 덮였다」로 읽는다.
try {
  paint(anchors, viewOf(state), create);
} catch {
  halt();
}

// 스트림 개설.
startStream();
