/**
 * 배선 층의 **순수 부분** — 정본은 `docs/WEB-UI.md` §9.4 결정 13(조회 통로)과 결정 11(표시
 * 판정)이다.
 *
 * §9.4 결정 7이 층을 갈랐다. 화면이 지는 것은 *"자리(앵커)만 제공"*이고 `/client/`의 모듈이
 * 그 자리를 채운다. **그 채우는 층이 배선이고, 이 파일은 그 층에서 DOM을 안 만지는 부분만
 * 든다.**
 *
 * **DOM을 실제로 만지는 부분은 오늘 0건이다.** 이 모듈이 여는 것은 통로이지 그리기가 아니고,
 * 그리기는 화면이 온 뒤에 붙는다 — §9.4가 *"오늘 반입할 수 있는 화면이 원격에 0장이다"*를
 * 스스로 적었다. 그래서 이 파일은 브라우저 전역에 **최상위에서도 함수 안에서도** 닿지 않는다.
 * 원천을 인자로 받기 때문이고, 그 배치가 node 환경의 계약 테스트가 이 모듈을 그대로 임포트할
 * 수 있는 근거다.
 *
 * **결정 11의 표시 판정도 이 모듈의 자리다** — 안전 사실 둘을 표시하는가는 앵커 이름의 문제가
 * 아니라 배선의 정책이라 `anchors.js`가 아니라 여기에 산다. **그 함수가 이 파일 말미에 섰다**
 * (`safetyDisplay`). 이 모듈이 드는 것이 통로 하나가 아니라 둘이 된 셈이고, 둘을 한 파일에
 * 두는 근거는 둘 다 배선의 순수 부분이라는 것 하나다 — 결정 11의 판정이
 * *"모집단은 화면이 아니라 배선이다"*로 자리를 지목한 그 층이다.
 *
 * ## 통로가 하나인 것이 계약이다 (결정 13)
 *
 * 그 항이 *"배선은 DOM 조회 API를 직접 부르지 않는다."*로 열고
 * *"앵커를 여는 통로는 하나이고 그 인자의 타입이 앵커 이름의 유니온이다."*를 계약으로 든다.
 * 목록 밖 이름은 타입 검사가 컴파일 시점에 잡고, *"변수를 거친 조회도 넓은 문자열 타입이 그
 * 유니온에 대입되지 않아"* 같은 자리에서 함께 잡힌다 — 텍스트 스캔이 못 보던 자리다.
 *
 * **이것은 §9.1이 traversal에 대해 쓴 수단과 같은 형태다.** 그 절이
 * *"요청에서 온 문자열이 파일 경로에 들어가지 않는다."*로 검사 대신 도달 불가를 골랐고, 여기서
 * 도달 불가가 되는 것은 **목록 밖 이름이 조회 인자로 들어가는 경로**다. §9.3이 이 디렉터리에
 * 타입 검사를 걸어 둔 것(`allowJs`·`checkJs`)이 그 수단을 실제로 세운다.
 *
 * ## 못 찾으면 던진다
 *
 * 결정 13이 *"못 찾으면 던진다."*를 따로 든 근거는 결정 8의 한계다 — 그 대조는 부분 문자열이라
 * 주석이나 문자열 안의 표기도 존재로 읽으므로 **그 그린이 런타임의 실재를 보장하지 않는다.**
 * 통로가 빈 값을 조용히 흘리면 그것이 `ARCHITECTURE.md` §2.6이 이름 붙인 실패다 —
 * *"조회가 아무것도 못 찾고 그리기가 그냥 안 일어난다"*.
 *
 * **[추정]** 던지는 오류의 타입은 표준 `Error`다. 결정 13이
 * *"던짐의 자리와 사용자가 보는 형태는 세부다."*로 닫았고, 배선이 갈래를 구별할 요구가 오늘
 * 없다. 요구가 나면 그때 좁힌다 — 넓히는 변경이라 계약 파기가 아니다.
 *
 * ## 이 모듈이 재지 못하는 것
 *
 * **배선이 이 통로를 우회해 DOM API를 직접 부르는 것.** 결정 13이 그 한계를 스스로 적었다 —
 * *"배선이 통로를 우회해 DOM API를 직접 부르는 것"*은 그것을 재려면 그 항이 정확히 거부한
 * 스캔이 필요하다. 재도입 트리거도 그 항이 든다:
 * *"배선이 통로 밖에서 DOM을 여는 것이 실제로 관측될 때"*.
 */

/**
 * 앵커 이름 하나. **정본은 `anchors.js`이고 여기서는 타입으로만 들여온다** — 이름을 두 번
 * 적으면 그 둘 사이의 일치가 새 부패 후보가 되고, 이 레포가 되풀이해 이름 붙인 형태다.
 * 선례는 `protocol.js`의 `@typedef` 열이다(그쪽은 프레임 유니온을 `../src/protocol.ts`에서
 * 같은 방식으로 들여온다).
 *
 * **런타임 임포트가 아니다.** 이 파일에 `anchors.js`의 값을 받아 오는 줄이 없다 — 통로가
 * 목록을 런타임에 다시 대조하면 그것은 타입이 이미 하는 일의 중복이고, 그 중복이 낡으면
 * 두 판정이 갈린다.
 *
 * @typedef {import("./anchors.js").AnchorName} AnchorName
 */

/**
 * 앵커를 여는 **원천**. 통로가 이것을 인자로 받으므로 이 모듈의 시그니처에 DOM 타입도 DOM
 * 전역도 나타나지 않는다.
 *
 * **왜 주입인가.** 전역을 직접 읽으면 이 모듈을 임포트하는 것만으로 브라우저 환경이 요구되고,
 * 그 요구를 테스트에서 채우는 수단은 새 의존성뿐이다 — `TECH-STACK.md` §7의 도구 체인 밖이고
 * `WEB-UI.md` §2.2의 예산 물음을 새로 연다. 주입은 이 레포가 이미 쓰는 형태다(`assets.ts`의
 * 읽기 주입 · 계약 테스트의 매니페스트 주입).
 *
 * 요소의 타입을 열어 둔 것도 같은 근거다. 좁히면 그 자리에 DOM 타입이 와야 하고, 그 순간
 * §9.3이 설정을 가르며 지킨 경계를 이 시그니처가 되돌린다.
 *
 * @template E
 * @typedef {{ getElementById(id: string): E | null }} AnchorSource
 */

/**
 * 앵커 하나를 연다. **`/client/`에서 앵커를 여는 자리는 이 함수 하나다**(§9.4 결정 13).
 *
 * 인자의 순서가 원천 먼저인 것은 세부다. 계약인 것은 셋이다 — 이름의 타입이 닫힌 유니온이라는
 * 것, 원천이 인자라는 것, 못 찾으면 던진다는 것.
 *
 * 오류가 **어느 이름을 못 찾았는지**를 든다. 문면은 세부이나 이름이 빠지면 던짐이 침묵보다
 * 조금 나은 정도로 내려간다 — 화면이 앵커 열 중 무엇을 빠뜨렸는지가 그 순간 안 보인다.
 *
 * @template E
 * @param {AnchorSource<E>} source
 * @param {AnchorName} name
 * @returns {E}
 */
export function anchorElement(source, name) {
  const found = source.getElementById(name);
  if (found === null) {
    throw new Error(`앵커 ${name}의 자리를 화면에서 찾지 못했다.`);
  }
  return found;
}

/**
 * 기동 시 동결된 안전 사실 둘. **정본은 `../src/protocol.ts`의 `StateSnapshot`이고 여기서는
 * 인덱스로 들여온다** — 값 도메인을 옮겨 적으면 `WEB-UI.md` §6.1이 그 필드를 넓히는 날 이쪽이
 * 조용히 낡는다. 그 파일이 이미 같은 이유로 도메인을 발명하지 않는다고 적었다.
 *
 * 선례는 위 앵커 이름과 같고, 인덱스 접근을 `import()` 안에서 쓰는 형태는 `protocol.js`가
 * `ServerEventFrame["event"]`로 이미 쓴다.
 *
 * @typedef {import("../src/protocol.ts").StateSnapshot["safety"]} SafetyFacts
 */

/**
 * 표시 판정이 채우는 자리. 키가 앵커 이름이고 `Extract`가 `anchors.js`의 유니온에서 그것을
 * 걸러 낸다.
 *
 * **그 강제의 실제 범위는 절반이다**(2026-08-27 독립 QA가 컴파일 변이로 쟀다). 두 이름 중
 * **한쪽만** 목록에서 빠지거나 개명되면 아래 함수의 반환 리터럴이 컴파일에서 붉는다. 그러나
 * **둘 다 사라지거나 둘 다 개명되면 안 붉는다** — `Extract`가 `never`로 붕괴하고
 * `Readonly<Record<never, boolean>>`가 빈 객체 타입이 되어 초과 속성 검사가 통째로 죽는다.
 *
 * **그 갈래를 잡는 것은 런타임 축이다.** `wiring.contract.test.ts`의 「판정이 채우는 두 자리가
 * 앵커 목록 안이다」 축과, 형제 독립 QA의 `safety-` 접두 자리를 세는 축이 삭제·개명을 둘 다
 * 붉힌다.
 * **계약은 지켜지고 있고, 여기서 고친 것은 무엇이 그것을 지키는가에 대한 서술이다** — 강제
 * 수단을 실제보다 넓게 적어 두면 `WEB-UI.md` §2.3이
 * *"검사가 실제보다 넓게 주장하는 것이 진짜 결함이었던 자리"*로 이름 붙인 형태를 이 주석이
 * 작게 되풀이한다.
 *
 * **타입을 더 닫지 않는다.** 두 이름이 유니온의 부분집합임을 요구하는 형태로 바꾸면 붕괴가
 * 막히나 §9.4가 요구한 바가 아니다 — 요구가 나면 그때가 그 판정의 자리다.
 *
 * @typedef {Extract<AnchorName, "safety-approval-mode" | "safety-sandbox">} SafetyAnchorName
 */

/**
 * 안전 사실 둘을 **그 자리에 채우는가**를 판정한다 (§9.4 결정 11).
 *
 * 결정 11이 `CLI-INTERFACE.md` §7.1의 조항을 승계하며 든 문장 그대로다 —
 * *"그래서 웹 화면도 `approvalMode`가 `manual`이고 `sandbox`가 `on`일 때 그 사실을 표시하지
 * 않는다."* 그 조항이 §7.1에서 단 근거는 대비의 보존이고
 * (*"그 상태를 매 순간 선언하면 표시가 소음이 되고 정작 내려간 순간의 대비가 죽는다"*)
 * 결정 11이 그 근거가 **호스트를 가리지 않는다**고 판정했으므로 웹에서도 같은 판정이 선다.
 *
 * **재는 것은 그 자리를 채우는가이지 무엇이 채워지는가가 아니다.** 뒤엣것은 배선의 그리기이고
 * 오늘 0건이다. 그래서 이 함수는 문면도 요소도 돌려주지 않는다 — 결정 10이
 * *"문면·자리·형태는 세부다"*로 닫은 것을 문자열을 고르는 순간 이 층이 계약으로 굳힌다.
 * §12도 같은 것을 *"결정 11이 요구한 표시 판정 함수의 문면"*으로 세부에 둔다.
 *
 * **자리는 판정과 무관하게 늘 있다.** 결정 11이 *"앵커는 값과 무관하게 항상 있다"*로 자리
 * 쪽의 승계를 끊었고, 거짓이 뜻하는 것은 앵커의 부재가 아니라 그 안이 비는 것이다 —
 * *"비어 있는 자리는 이 화면의 정상 상태다."*
 *
 * **두 항목은 서로 독립이다.** §7.1의 내용 표가 둘을 각자의 행으로 들고 출처도 갈린다(설정
 * 동결과 5b 판정 동결). 한쪽만 내려간 조합이 실재하므로 한 판정이 둘을 함께 켜면 그것은
 * 사용자가 내리지 않은 결정을 화면이 지어내는 것이 된다.
 *
 * @param {SafetyFacts} safety
 * @returns {Readonly<Record<SafetyAnchorName, boolean>>}
 */
export function safetyDisplay(safety) {
  return {
    // 승인 모드가 `off`임 — §7.1 내용 표의 첫째 계약 행.
    "safety-approval-mode": safety.approvalMode === "off",
    // 셸이 호스트에서 돎 — 같은 표의 둘째 계약 행. 위와 같은 표기를 쓰지만 **같은 값이 아니다**:
    // 두 필드의 기본값이 다르고(`manual`·`on`) 여기서 갈리는 것은 각자의 내려간 값이다.
    "safety-sandbox": safety.sandbox === "off",
  };
}
